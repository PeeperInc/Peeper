function scoreHit(dist) {
  if (dist <= R_INNER) return { pts: 3, label: '🎯 BULLSEYE!', color: '#ff3355' };
  if (dist <= R_MID)   return { pts: 2, label: '👌 Middle!',   color: '#ffd700' };
  if (dist <= R_OUTER) return { pts: 1, label: '😐 Edge',      color: '#aaaaaa' };
  return                      { pts: 0, label: '💨 Miss',       color: '#555555' };
}

export default function SniperGame({ onComplete, onClose }) {
  const [shots, setShots]    = useState([]);
  const [totalPts, setTotal] = useState(0);
  const [lastHit, setLastHit]= useState(null);
  const [phase, setPhase]    = useState('playing');
  const [result, setResult]  = useState(null);
  const rafRef         = useRef(null);
  const crosshairElRef = useRef(null);
  const targetElRef    = useRef(null);
  const shotsRef       = useRef([]);
  const totalRef       = useRef(0);
  const crosshairRef   = useRef({ x: 0, y: 0 });
  const lastShotRef    = useRef(0);
  shotsRef.current = shots;
  totalRef.current = totalPts;

  useEffect(() => {
    // No math in RAF — just read pre-computed array index
    const N = ROSE_PATH.length;
    let idx  = 0;
    let bobT = 0;
    let lastTime = null;
    // Speed: steps per second through the array
    // Array has ~2842 points for full 2π loop → ~450 steps/s feels right
    const STEPS_PER_SEC = 900;

    function tick(now) {
      if (lastTime === null) lastTime = now;
      const dt = Math.min((now - lastTime) / 1000, 0.05);
      lastTime = now;

      idx  = (idx + STEPS_PER_SEC * dt) % N;
      bobT += dt;

      const [cx, cy] = ROSE_PATH[Math.floor(idx)];
      const bobX = Math.sin(bobT * 0.65 + 1) * 11;
      const bobY = Math.sin(bobT * 1.05) * 18;

      crosshairRef.current = { x: cx, y: cy };
      if (crosshairElRef.current) {
        crosshairElRef.current.style.transform =
          `translate(calc(-50% + ${bobX + cx}px), calc(-50% + ${bobY + cy}px))`;
      }
      if (targetElRef.current) {
        targetElRef.current.style.transform =
          `translate(calc(-50% + ${bobX}px), calc(-50% + ${bobY}px))`;
      }
      rafRef.current = requestAnimationFrame(tick);
    }
    rafRef.current = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(rafRef.current);
  }, []);

  const handleShot = useCallback((e) => {
    if (phase !== 'playing') return;
    if (e.type === 'mousedown' && e.button !== 0) return;
    const current = shotsRef.current;
    if (current.length >= MAX_SHOTS) return;
    const now = Date.now();
    if (now - lastShotRef.current < 500) return; // 0.5s cooldown
    lastShotRef.current = now;
    e.preventDefault(); e.stopPropagation();

    // Shot lands where the animated crosshair currently is
    const dx = crosshairRef.current.x;
    const dy = crosshairRef.current.y;
    const dist = Math.sqrt(dx*dx + dy*dy);
    const hit  = scoreHit(dist);
    const newShots = [...current, { x: dx, y: dy, ...hit }];
    const newTotal = totalRef.current + hit.pts;
    setShots(newShots); setTotal(newTotal);
    setLastHit(hit); setTimeout(() => setLastHit(null), 900);

    if (newShots.length >= MAX_SHOTS) {
      setTimeout(() => {
        const allHit = newShots.every(s => s.pts > 0);
        const bonus  = allHit ? 1 : 0;
        const final  = Math.min(10, newTotal + bonus);
        setResult({ bonus, final, allHit, shots: newShots, total: newTotal });
        setPhase('result');
      }, 900);
    }
  }, [phase]);

  if (phase === 'result' && result) {
    return (
      <div style={FULLSCREEN}>
        <div style={{ position:'absolute', inset:0, background:'linear-gradient(180deg,#0a0e1a,#1a1a2e)' }} />
        <div style={RESULT_CARD}>
          <div style={{ fontSize:48, marginBottom:4 }}>🎯</div>
          <div style={{ fontSize:26, fontWeight:900, color:'#ffd700', textShadow:'2px 2px 0 #000', marginBottom:16 }}>Results</div>
          <div style={{ width:'100%', marginBottom:12 }}>
            {result.shots.map((s, i) => (
              <div key={i} style={{ display:'flex', justifyContent:'space-between', alignItems:'center',
                padding:'6px 8px', marginBottom:4, background:'rgba(255,255,255,0.04)', borderRadius:8 }}>
                <span style={{ color:'#aaa' }}>Shot {i+1}</span>
                <span style={{ color:s.color, fontWeight:700 }}>{s.label}</span>
                <span style={{ color:'#ffd700', fontWeight:700 }}>+{s.pts} pts</span>
              </div>
            ))}
          </div>
          {result.allHit && (
            <div style={{ color:'#aaffaa', fontSize:14, fontWeight:700, padding:'8px 16px',
              background:'rgba(100,220,100,0.12)', borderRadius:8, marginBottom:12,
              border:'1px solid rgba(100,220,100,0.2)' }}>
              🎖 All 3 hit! Bonus +1 ✦
            </div>
          )}
          <div style={{ fontSize:22, fontWeight:900, color:'#fff', margin:'4px 0 20px' }}>
            Total: <span style={{ color:'#ffd700' }}>{result.final} ✦</span>
          </div>
          <button onClick={() => onComplete(result.final, result.final > 0)} style={BTN}>
            Collect coins!
          </button>
        </div>
      </div>
    );
  }

  return (
    <div style={{ ...FULLSCREEN, cursor:'crosshair' }}
      onMouseDown={handleShot} onTouchStart={handleShot}>
      <div style={{ position:'absolute', inset:0, background:'linear-gradient(180deg,#0a0e1a,#1a1a2e)' }} />

      {/* Grid — static, no re-computation */}
      <svg style={{ position:'absolute', inset:0, width:'100%', height:'100%', opacity:0.06, pointerEvents:'none' }}>
        {GRID_LINES.map((_,i) => (
          <React.Fragment key={i}>
            <line x1={i*5+'%'} y1="0" x2={i*5+'%'} y2="100%" stroke="#6688aa" strokeWidth="1"/>
            <line x1="0" y1={i*5+'%'} x2="100%" y2={i*5+'%'} stroke="#6688aa" strokeWidth="1"/>
          </React.Fragment>
        ))}
      </svg>



      {/* Target */}
      <div ref={targetElRef} style={{
        position:'absolute', left:'50%', top:'42%',
        transform:`translate(-50%, -50%)`,
        width:TARGET_D, height:TARGET_D,
        userSelect:'none', pointerEvents:'none',
        filter:'drop-shadow(0 6px 28px rgba(0,0,0,0.8))',
        willChange:'transform',
      }}>
        <svg width={TARGET_D} height={TARGET_D}
          viewBox={`${-R_OUTER} ${-R_OUTER} ${TARGET_D} ${TARGET_D}`}>
          {/* Outer ring - pre-computed */}
          {OUTER_PATHS.map((p,i) => <path key={i} d={p.d} fill={p.fill} />)}
          {/* Middle ring */}
          <circle cx="0" cy="0" r={R_MID} fill="#1a1a1a"/>
          {MID_PATHS.map((p,i) => <path key={i} d={p.d} fill={p.fill} />)}
          {/* Bullseye */}
          <circle cx="0" cy="0" r={R_INNER} fill="#cc2222"/>
          <circle cx="0" cy="0" r="10"      fill="#ff5577"/>
          <circle cx="0" cy="0" r="4"       fill="#fff" opacity="0.6"/>
          {/* Crosshair */}
          <line x1="0" y1={-R_OUTER} x2="0" y2={R_OUTER} stroke="rgba(0,0,0,0.2)" strokeWidth="1.5"/>
          <line x1={-R_OUTER} y1="0" x2={R_OUTER} y2="0" stroke="rgba(0,0,0,0.2)" strokeWidth="1.5"/>
          {/* Point labels */}
          <text x={R_MID+6} y="5"    fill="rgba(255,255,255,0.45)" fontSize="12" fontFamily="system-ui">1</text>
          <text x={R_INNER+4} y="5"  fill="rgba(255,255,255,0.6)"  fontSize="12" fontFamily="system-ui">2</text>
          <text x="-5" y="6"          fill="white"                  fontSize="13" fontWeight="bold" fontFamily="system-ui">3</text>
          {/* Bullet holes */}
          {shots.map((s, i) => (
            <g key={i}>
              <circle cx={s.x} cy={s.y} r="8"  fill="#000" opacity="0.9"/>
              <circle cx={s.x} cy={s.y} r="8"  fill="none" stroke="#555" strokeWidth="1.5"/>
              <circle cx={s.x-2} cy={s.y-2} r="2.5" fill="#2a2a2a"/>
            </g>
          ))}
        </svg>
      </div>

      {/* Animated crosshair — floats over the target, driven by direct DOM update */}
      <div ref={crosshairElRef} style={{
        position:'absolute', left:'50%', top:'42%',
        transform:'translate(-50%, -50%)',
        pointerEvents:'none', zIndex:20,
        willChange:'transform',
      }}>
        <svg width="64" height="64" viewBox="-32 -32 64 64">
          <circle cx="0" cy="0" r="26" fill="none" stroke="rgba(255,255,255,0.7)" strokeWidth="1.8"/>
          <line x1="0" y1="-32" x2="0" y2="-12" stroke="rgba(255,255,255,0.7)" strokeWidth="1.8"/>
          <line x1="0" y1="12"  x2="0" y2="32"  stroke="rgba(255,255,255,0.7)" strokeWidth="1.8"/>
          <line x1="-32" y1="0" x2="-12" y2="0" stroke="rgba(255,255,255,0.7)" strokeWidth="1.8"/>
          <line x1="12"  y1="0" x2="32"  y2="0" stroke="rgba(255,255,255,0.7)" strokeWidth="1.8"/>
          <circle cx="0" cy="0" r="3.5" fill="rgba(255,50,50,0.95)"/>
        </svg>
      </div>

      {/* Hit flash */}
      {lastHit && (
        <div style={{ position:'absolute', top:'17%', left:'50%',
          transform:'translateX(-50%)', fontSize:22, fontWeight:900,
          color:lastHit.color, textShadow:'2px 2px 0 #000', whiteSpace:'nowrap',
          pointerEvents:'none', zIndex:20, animation:'popIn 0.25s cubic-bezier(0.175,0.885,0.32,1.275)' }}>
          {lastHit.label} <span style={{ color:'#ffd700' }}>+{lastHit.pts}</span>
        </div>
      )}

      {/* HUD */}
      <div style={{ position:'absolute', top:16, left:0, right:0,
        display:'flex', justifyContent:'space-between', padding:'0 20px',
        pointerEvents:'none', zIndex:10 }}>
        <div style={{ display:'flex', gap:6 }}>
          {Array.from({length:MAX_SHOTS}).map((_,i) => (
            <span key={i} style={{ fontSize:22, opacity: i < (MAX_SHOTS-shots.length) ? 1 : 0.2 }}>🔫</span>
          ))}
        </div>
        <div style={{ color:'#ffd700', fontSize:16, fontWeight:700,
          background:'rgba(0,0,0,0.4)', padding:'4px 12px', borderRadius:8 }}>
          {totalPts} / {MAX_SHOTS*3} pts
        </div>
      </div>

      {/* Legend */}
      <div style={{ position:'absolute', bottom:52, left:0, right:0,
        display:'flex', justifyContent:'center', gap:20, pointerEvents:'none', zIndex:10 }}>
        {[['🔴','Center','3 pts'],['⚫','Middle','2 pts'],['⚪','Edge','1 pt']].map(([ic,n,p]) => (
          <div key={n} style={{ textAlign:'center' }}>
            <div style={{ fontSize:18 }}>{ic}</div>
            <div style={{ color:'#fff', fontSize:11, fontWeight:700 }}>{n}</div>
            <div style={{ color:'#ffd700', fontSize:11 }}>{p}</div>
          </div>
        ))}
      </div>
      <div style={{ position:'absolute', bottom:22, left:0, right:0, textAlign:'center',
        color:'rgba(100,220,100,0.6)', fontSize:12, pointerEvents:'none', zIndex:10 }}>
        All 3 hit → +1 bonus ✦ · Max 10 ✦
      </div>

      {/* Close */}
      <button onClick={e => { e.stopPropagation(); onClose(); }}
        style={{ position:'absolute', top:10, right:14, background:'rgba(0,0,0,0.5)',
          border:'none', color:'#aaa', fontSize:22, cursor:'pointer', padding:'4px 10px',
          borderRadius:8, zIndex:20 }}>✕</button>

      <style>{`@keyframes popIn{from{transform:translateX(-50%) scale(0.4);opacity:0}to{transform:translateX(-50%) scale(1);opacity:1}}`}</style>
    </div>
  );
}

